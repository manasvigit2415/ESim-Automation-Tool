"""Configuration handling: PATH / environment setup for eSim.

`apply_environment` writes
  * esim_env.sh / esim_env.bat : source it to put every tool on PATH
  * tools_state.json           : machine-readable paths + versions that eSim
                                 (or any script) can read instead of guessing
"""
from __future__ import annotations

import json
import os
import shlex
from pathlib import Path
from typing import Dict, List

from . import platform_utils as pu
from .logger import home_dir
from .manager import ToolManager

MARKER = "# esim-tool-manager"


def collect(mgr: ToolManager) -> Dict[str, dict]:
    state = {}
    for t in mgr.registry.values():
        st = mgr.status(t)
        state[t.id] = {"installed": st.installed, "version": st.version, "path": st.path}
    return state


def apply_environment(mgr: ToolManager, persist: bool = False) -> List[Path]:
    state = collect(mgr)
    home = home_dir()
    dirs: List[str] = list(mgr.config.get("extra_paths") or [])
    exports: Dict[str, str] = {}
    for tid, info in state.items():
        if info["path"]:
            d = os.path.dirname(info["path"])
            if d not in dirs and d not in os.environ.get("PATH", "").split(os.pathsep):
                dirs.append(d)
            exports[f"ESIM_{tid.upper()}_BIN"] = info["path"]
    exports.update(mgr.config.get("extra_env") or {})

    state_file = home / "tools_state.json"
    state_file.write_text(json.dumps(state, indent=2), encoding="utf-8")
    written = [state_file]

    if pu.os_name() == "windows":
        env_file = home / "esim_env.bat"
        lines = ["@echo off", "REM Generated by esim-tool-manager"]
        lines += [f'set "PATH={d};%PATH%"' for d in dirs]
        lines += [f'set "{k}={v}"' for k, v in exports.items()]
        env_file.write_text("\r\n".join(lines) + "\r\n", encoding="utf-8")
        mgr.say(f"Wrote {env_file}. Run it in a terminal before launching eSim.")
    else:
        env_file = home / "esim_env.sh"
        lines = ["# Generated by esim-tool-manager"]
        if dirs:
            lines.append(f'export PATH={shlex.quote(os.pathsep.join(dirs))}:"$PATH"')
        lines += [f"export {k}={shlex.quote(v)}" for k, v in exports.items()]
        env_file.write_text("\n".join(lines) + "\n", encoding="utf-8")
        mgr.say(f"Wrote {env_file}. Use: source {env_file}")
        if persist:
            rc = Path.home() / (".zshrc" if pu.os_name() == "darwin" else ".bashrc")
            text = rc.read_text(encoding="utf-8") if rc.exists() else ""
            if MARKER not in text:
                with open(rc, "a", encoding="utf-8") as fh:
                    fh.write(f'\n[ -f "{env_file}" ] && . "{env_file}" {MARKER}\n')
                mgr.say(f"Added a source line to {rc}")
            else:
                mgr.say(f"{rc} already sources the environment file")
    written.append(env_file)
    mgr.actions.record("config-apply", "all", "success", f"wrote {env_file.name}")
    return written
